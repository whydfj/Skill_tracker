try:
    from gigachat import GigaChat  # type: ignore
except ImportError:  # pragma: no cover - внешняя опциональная зависимость
    GigaChat = None  # type: ignore


router = APIRouter(tags=["AI Assistant"])


def _get_gigachat_client() -> Optional["GigaChat"]:
    """
    Пытаемся инициализировать GigaChat-клиент, если установлен пакет и есть креды.
    Если чего‑то не хватает — возвращаем None и используем локальный генератор.
    """
    if GigaChat is None:
        return None

    credentials = os.getenv("GIGACHAT_CREDENTIALS")
    if not credentials:
        return None

    return GigaChat(credentials=credentials, verify_ssl_certs=False)


def _local_completion(question: str) -> str:
    """
    Локальный генератор ответов по документации Curse_work.
    Пытается понять тему вопроса по ключевым словам и дать осмысленный ответ.
    """
    q = question.lower()

    # Вход / авторизация
    if any(w in q for w in ["логин", "вход", "авториза", "sign in", "login"]):
        return (
            "Авторизация в Curse_work устроена так:\n"
            "1. Пользователь вводит логин и пароль на странице входа.\n"
            "2. После успешной проверки создаётся сессия и вы попадаете в интерфейс в зависимости от вашей роли "
            "(администратор, менеджер или сотрудник).\n"
            "3. При выходе из системы сессия очищается, и для повторного входа нужно снова указать логин и пароль.\n"
            "4. Если данные неверны, сервер вернёт ошибку, и вход выполнен не будет."
        )

    # Роли и права
    if any(w in q for w in ["роль", "права", "admin", "менеджер", "руководител", "user", "сотрудник"]):
        return (
            "В Curse_work есть три основных роли с разными правами:\n"
            "1. Администратор (admin) — управляет пользователями: создаёт и удаляет аккаунты, может видеть всех "
            "пользователей и управлять всеми задачами.\n"
            "2. Менеджер (manager) — отвечает за задачи: создаёт, редактирует и удаляет задачи, назначает их "
            "конкретным пользователям, может менять дедлайны и смотреть прогресс.\n"
            "3. Пользователь/сотрудник (user) — видит только свои задачи, может обновлять прогресс по каждой задаче "
            "и оставлять комментарии.\n"
            "Фактическое поведение реализовано через проверки роли на сервере перед выполнением чувствительных операций."
        )

    # Задачи
    if any(w in q for w in ["задач", "task", "таск", "назначить", "создать задачу", "управление задачами"]):
        return (
            "Работа с задачами в Curse_work устроена так:\n"
            "1. Менеджер или администратор создаёт задачу, указывая пользователя, заголовок, описание и при необходимости дедлайн.\n"
            "2. Для каждого пользователя есть отдельный список \"Мои задачи\", где он видит только свои активные задачи.\n"
            "3. Пользователь может обновлять прогресс (0–100%), а менеджер и администратор видят этот прогресс в общем списке.\n"
            "4. Через интерфейс менеджера доступны действия: редактирование названия/описания, изменение дедлайна и удаление задач.\n"
            "5. На уровне API используются отдельные эндпоинты для получения своих задач, задач конкретного пользователя и всех задач."
        )

    # Комментарии
    if any(w in q for w in ["коммент", "comment"]):
        return (
            "Система комментариев в Curse_work привязана к задачам:\n"
            "1. Комментарий всегда относится к конкретной задаче и конкретному пользователю-автору.\n"
            "2. Добавлять комментарии могут пользователи, у которых есть доступ к задаче (обычно исполнитель и менеджер).\n"
            "3. Каждый комментарий хранит текст, автора и время создания; при необходимости можно прикрепить файл.\n"
            "4. Пользователь может удалить только свои комментарии — это проверяется по его идентификатору на сервере.\n"
            "5. В интерфейсе комментарии отображаются под задачей с именем автора и временной меткой."
        )

    # Настройки
    if any(w in q for w in ["настройк", "язык", "theme", "тема", "интерфейс"]):
        return (
            "Раздел настроек в Curse_work позволяет пользователю персонализировать интерфейс:\n"
            "1. Можно сменить язык приложения (например, русский или английский) — это влияет на тексты и подписи.\n"
            "2. Можно выбрать тему оформления (например, светлую или тёмную), что меняет цветовую палитру UI.\n"
            "3. Настройки сохраняются в таблице User_settings и привязаны к конкретному пользователю.\n"
            "4. При изменении параметров интерфейс перерисовывается с учётом новых значений.\n"
            "5. Эти настройки не влияют на права доступа или бизнес-логику — только на внешний вид и язык."
        )

    # Общий ответ по приложению
    return (
        "Я отвечаю по функционалу приложения Curse_work.\n"
        "Судя по вашему вопросу, вам нужно общее описание:\n"
        "1. В системе есть аутентификация по логину и паролю и распределение ролей (администратор, менеджер, сотрудник).\n"
        "2. Основной блок — управление задачами: создание, назначение сотрудникам, установка дедлайнов и отслеживание прогресса.\n"
        "3. Для задач доступны комментарии, чтобы фиксировать обсуждения и уточнения.\n"
        "4. Пользователь видит только свои задачи, а менеджер и администратор — более широкий набор данных.\n"
        "5. В разделе настроек можно изменить язык и тему интерфейса. Уточните, пожалуйста, про какой именно раздел или действие вы хотите узнать подробнее."
    )


def _local_task_completion(title: str, username: str, draft: str) -> str:
    title = title.strip()
    username = username.strip()
    draft = draft.strip()

    base = f"Задача для сотрудника {username}: {title}.\n\n"

    # Специальный случай: курсовые / отчёты / учебные работы
    t_lower = title.lower()
    if any(w in t_lower for w in ["курсов", "диплом", "отчет", "отчёт", "исследован", "работа"]):
        return (
            base
            + "Техническое задание:\n"
            "1. Подготовить структурированную письменную работу по выбранной теме, включающую введение, основную часть и заключение.\n"
            "2. Во введении кратко обосновать актуальность темы, цель и задачи работы.\n"
            "3. В основной части раскрыть теоретические основы темы, описать ключевые понятия и существующие подходы.\n"
            "4. Проанализировать актуальные исследования, статистику или практические примеры, связанные с темой.\n"
            "5. В заключении сформулировать выводы по проделанной работе и указать возможные направления дальнейших исследований.\n"
            "6. Объём и требования к оформлению (шрифт, интервалы, стиль ссылок) должны соответствовать внутренним стандартам организации или вуза.\n"
            f"{'Черновое описание менеджера: ' + draft if draft else ''}"
        )

    # Для прочих задач — универсальное, но осмысленное ТЗ
    parts = [
        "Техническое задание:\n",
        "1. Чётко определить цель задачи — что должно быть получено в результате её выполнения.\n",
        "2. Описать основной перечень действий, которые нужно выполнить сотруднику для достижения результата.\n",
        "3. Уточнить формат итогового результата (документ, отчёт, презентация, реализованный функционал в системе и т.п.).\n",
        "4. При необходимости указать внешние зависимости: исходные данные, доступы, системы, с которыми нужно интегрироваться.\n",
        "5. Задать критерии приёмки: по каким признакам менеджер поймёт, что задача выполнена корректно.\n",
    ]

    if draft:
        parts.append(f"6. Учитывать дополнительные пожелания из чернового описания менеджера: {draft}.\n")

    return base + "".join(parts)


@router.post("/ai_request")
async def request_to_ai(user_request: AI_Request_Schema) -> str:
    """
    Отвечает на вопросы о работе приложения Curse_work, опираясь на шаблон описания.
    При наличии GigaChat и кредов использует внешнюю нейросеть, иначе — локальный генератор.
    """
    client = _get_gigachat_client()
    prompt = template + user_request.question

    if client is None:
        return _local_completion(user_request.question)

    response = client.chat(prompt)
    try:
        return response.choices[0].message.content
    except Exception:  # pragma: no cover - защита от изменений внешнего API
        return _local_completion(user_request.question)


@router.post("/ai_task_autocomplete")
async def ai_task_autocomplete(payload: Task_AI_Request_Schema):
    """
    Автодописывает / расширяет описание задачи за менеджера.
    Использует заголовок задачи, пользователя и черновое описание.
    """
    client = _get_gigachat_client()
    if client is None:
        suggested = _local_task_completion(
            title=payload.title,
            username=payload.username,
            draft=payload.draft_description,
        )
        return {"suggested_description": suggested}

    prompt = (
        "Ты выступаешь как менеджер, который формализует и дописывает описание задачи "
        "для сотрудника в корпоративной системе управления задачами.\n\n"
        f"Сотрудник: {payload.username}\n"
        f"Название задачи: {payload.title}\n"
        f"Черновое описание менеджера: {payload.draft_description}\n\n"
        "Сформулируй одно связное, подробное текстовое описание задачи на русском языке, "
        "подходящее для поля 'Описание' в таск‑трекере. Не используй разметку и списки — "
        "только обычный текст из нескольких предложений."
    )

    response = client.chat(prompt)
    try:
        text = response.choices[0].message.content
    except Exception:  # pragma: no cover
        text = _local_task_completion(
            title=payload.title,
            username=payload.username,
            draft=payload.draft_description,
        )

    return {"suggested_description": text}

